#!/bin/sh
# Read-only check that the store and agent files match this skill: agent instruction blocks,
# store layout, topic index, hippo skills and their links, budgets and formats.
# Prints each problem; exit 1 if any.
# Lines starting with "warn:" are advice and do not fail the check.
set -eu
export LC_ALL=en_US.UTF-8
here=$(cd "$(dirname "$0")" && pwd)
bad=0
say() { echo "$1"; bad=1; }
chars() { wc -m < "$1" | tr -d ' '; }

# every agent present must carry exactly block.md in its instruction file
for f in .claude/CLAUDE.md .codex/AGENTS.md .pi/agent/AGENTS.md; do
  [ -d "$HOME/$(dirname "$f")" ] || continue
  f=$HOME/$f
  n=$(grep -c '^<hippo>$' "$f" 2>/dev/null || true)
  if [ "${n:-0}" -eq 0 ]; then say "$f: no <hippo> block; run init_hippo.sh"
  elif [ "$n" -gt 1 ]; then say "$f: $n <hippo> blocks; keep one, then run init_hippo.sh"
  elif ! sed -n '/^<hippo>$/,/^<\/hippo>$/p' "$f" | cmp -s - "$here/../block.md"; then
    say "$f: <hippo> block differs from block.md; run init_hippo.sh"
  fi
  if grep -q '^</*memory-hippo>$' "$f" 2>/dev/null; then
    say "$f: old <memory-hippo> block from an earlier hippo; delete that block, keep <hippo>"
  fi
done

dir=${HIPPO_DIR:-$HOME/.hippo}
[ -d "$dir/.git" ] || { say "$dir: no store; run init_hippo.sh"; exit 1; }
cd "$dir"

# the store holds only the layout in SKILL.md; anything else is left over from an older one
for f in * .[!.]*; do
  [ -e "$f" ] || continue
  case $f in
    MEMORY.md|TOPIC_INDEX.md|topics|skills|PENDING.md|PENDING.reflecting.md|.git|.gitignore|.DS_Store) ;;
    *) say "$f: not part of the store layout in SKILL.md; move its content where SKILL.md says, then remove it" ;;
  esac
done

if [ -f MEMORY.md ]; then
  n=$(chars MEMORY.md)
  [ "$n" -le 4000 ] || say "MEMORY.md: $n chars, over 4000; compress or move detail to topics"
else
  say "MEMORY.md: missing"
fi

count=0
for f in topics/* topics/.[!.]*; do
  [ -e "$f" ] || continue
  b=${f#topics/}
  [ "$b" = .gitkeep ] && continue
  if ! echo "$b" | grep -Eq '^[a-z0-9][a-z0-9-]*\.md$'; then
    say "$f: topics hold only lowercase-kebab .md files"; continue
  fi
  count=$((count + 1))
  n=$(chars "$f")
  [ "$n" -le 8000 ] || say "$f: $n chars, over 8000; compress, merge, or drop least important"
  sed -n 1p "$f" | grep -q '^# ' || say "$f: line 1 must be '# <name>'"
  sed -n 2p "$f" | grep -Eq '^[^-#[:space:]]' || say "$f: line 2 must be a one-line scope"
done
[ "$count" -le 20 ] || say "topics: $count files, over 20; merge topics"

# TOPIC_INDEX.md is regenerated by sync_hippo.sh; never edit it
if [ ! -f TOPIC_INDEX.md ]; then
  say "TOPIC_INDEX.md: missing; run sync_hippo.sh"
else
  for f in topics/*.md; do
    [ -e "$f" ] || continue
    grep -qFx -- "- $f: $(sed -n 2p "$f")" TOPIC_INDEX.md || say "$f: missing or stale in TOPIC_INDEX.md; run sync_hippo.sh"
  done
  for f in $(sed -n 's/^- \(topics\/[a-z0-9-]*\.md\):.*/\1/p' TOPIC_INDEX.md); do
    [ -e "$f" ] || say "$f: indexed but does not exist; run sync_hippo.sh"
  done
fi

# hippo skills: skills/<name>/SKILL.md with frontmatter name and description, plus any files
count=0
for s in skills/* skills/.[!.]*; do
  [ -e "$s" ] || continue
  n=${s#skills/}
  [ "$n" = .gitkeep ] && continue
  if [ ! -d "$s" ] || ! echo "$n" | grep -Eq '^[a-z0-9][a-z0-9-]*$'; then
    say "$s: skills hold only lowercase-kebab folders"; continue
  fi
  [ "$n" != hippo ] || say "$s: the name hippo is taken by this skill; rename it"
  count=$((count + 1))
  f=$s/SKILL.md
  [ -f "$f" ] || { say "$f: missing"; continue; }
  c=$(chars "$f")
  [ "$c" -le 8000 ] || say "$f: $c chars, over 8000; compress or move detail to reference files"
  fm=$(awk 'NR == 1 { if ($0 != "---") exit; next } /^---$/ { exit } { print }' "$f")
  echo "$fm" | grep -qx "name: $n" || say "$f: frontmatter must start with --- and hold 'name: $n'"
  echo "$fm" | grep -Eq '^description: .{20,}' || say "$f: frontmatter needs a description of when to use it"
done
[ "$count" -le 20 ] || say "skills: $count folders, over 20; merge or remove skills"

# every hippo skill is linked into each agent skills folder; links are made by sync_hippo.sh
abs=$(pwd -P)/skills
for d in "$HOME/.claude/skills" "$HOME/.agents/skills"; do
  case $d in
    */.claude/*) [ -d "$HOME/.claude" ] || continue ;;
    *) [ -d "$HOME/.codex" ] || [ -d "$HOME/.pi/agent" ] || continue ;;
  esac
  for s in skills/*/; do
    [ -f "${s}SKILL.md" ] || continue
    n=${s#skills/}; n=${n%/}; l=$d/$n
    if [ -L "$l" ] && [ "$(readlink "$l")" = "$abs/$n" ]; then continue; fi
    if [ -e "$l" ] || [ -L "$l" ]; then say "$l: name taken by another skill; rename skills/$n"
    else say "$l: missing link; run sync_hippo.sh"; fi
  done
  for l in "$d"/* "$d"/.[!.]*; do
    [ -L "$l" ] || continue
    t=$(readlink "$l")
    case $t in "$abs"/*)
      if [ "$t" != "$abs/${l##*/}" ] || [ ! -f "$t/SKILL.md" ]; then say "$l: stale link; run sync_hippo.sh"; fi ;;
    esac
  done
done

set -- MEMORY.md
for f in topics/*.md; do [ -e "$f" ] && set -- "$@" "$f"; done
if grep -inE '^(- )?20[0-9]{2}-[0-9]{2}-[0-9]{2}:|\((as of )?20[0-9]{2}-[0-9]{2}-[0-9]{2}' "$@" 2>/dev/null; then
  say 'date stamps in the lines above; write a date inside a fact (like a deadline), not as a line or paren stamp'
fi

today=$(date +%F)
for f in "$@"; do
  for d in $(grep -oE '20[0-9]{2}-[0-9]{2}-[0-9]{2}' "$f" | sort -u); do
    if [ "$d" \> "$today" ]; then echo "warn: $f: date $d is in the future; fine for a deadline, otherwise fix it"; fi
  done
done

if grep -lE '^(<<<<<<<|>>>>>>>)' "$@" 2>/dev/null; then
  say "conflict markers in the files above"
fi

# the same path or issue number in several files often means one fact kept in two places
for f in "$@"; do
  grep -oE '~/[A-Za-z0-9._/-]*[A-Za-z0-9_/-]|#[0-9]+' "$f" | sort -u | sed "s|\$|	$f|"
done | awk -F'\t' '{ n[$1]++; at[$1] = at[$1] " " $2 }
  END { for (t in n) if (n[t] > 1) print "warn: " t " appears in" at[t] }' | sort

[ "$bad" -eq 0 ] && echo ok
exit "$bad"
